bool McpServer::supportsProtocol(const std::string& v) {
    return std::find(std::begin(kProtocols), std::end(kProtocols), v) != std::end(kProtocols);
}
const char* McpServer::latestProtocol() { return kProtocols[0]; }

fs::path McpServer::mapDir() {
    fs::path d;
    queue_.post([&] { d = editor_.world.dir; }).wait();
    return d;
}

json McpServer::toolList() const {
    json tools = json::array();
    for (const Tool& t : editor_.tools()) {
        bool readOnly = t.category == ToolCategory::Read;
        json annotations = {{"readOnlyHint", readOnly}, {"destructiveHint", t.name == "delete" || t.name == "terrain_generate"},
                            {"idempotentHint", readOnly}, {"openWorldHint", false}};
        json schema = t.schema;
        if (!schema.contains("properties")) schema["properties"] = json::object();
        tools.push_back({{"name", t.name}, {"title", t.title.empty() ? toolTitle(t.name) : t.title}, {"description", t.description},
                         {"inputSchema", schema}, {"annotations", annotations}});
    }
    return tools;
}

json McpServer::resourceList() {
    json out = json::array();
    for (const DocResource& d : kDocs) {
        std::error_code ec;
        fs::path p = editor_.options.docsDir / d.file;
        if (!fs::is_regular_file(p, ec)) continue;
        json r = {{"uri", std::string("dayfall://docs/") + d.name}, {"name", d.name}, {"title", d.title}, {"description", d.description},
                  {"mimeType", "text/markdown"}};
        if (auto size = fs::file_size(p, ec); !ec) r["size"] = size;
        out.push_back(r);
    }
    out.push_back({{"uri", "dayfall://map/document"}, {"name", "map-document"}, {"title", "Map document (live)"},
                   {"description", "The open map's map.json as it is in the editor now, unsaved edits included."},
                   {"mimeType", "application/json"}});
    for (const CaptureFile& c : newestCaptures(mapDir(), 20)) {
        std::string file = c.path.filename().string();
        json r = {{"uri", "dayfall://captures/" + file}, {"name", file}, {"title", "Capture " + c.path.stem().string()},
                  {"description", "A capture saved under <map>/captures/ (newest first)."}, {"mimeType", imageMime(c.path)}, {"size", c.size}};
        auto sys = std::chrono::floor<std::chrono::seconds>(std::chrono::file_clock::to_sys(c.time));
        r["annotations"] = {{"audience", {"user", "assistant"}}, {"lastModified", std::format("{:%FT%TZ}", sys)}};
        out.push_back(r);
    }
    return out;
}

