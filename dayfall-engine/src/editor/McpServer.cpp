json rpcError(const json& id, int code, const std::string& msg, json data = nullptr) {
    json e = {{"code", code}, {"message", msg}};
    if (!data.is_null()) e["data"] = std::move(data);
    return {{"jsonrpc", "2.0"}, {"id", id}, {"error", e}};
}
json rpcResult(const json& id, json result) { return {{"jsonrpc", "2.0"}, {"id", id}, {"result", std::move(result)}}; }
// never throws on bad UTF-8 (file names, log lines)
std::string dumpJson(const json& j, int indent = -1) { return j.dump(indent, ' ', false, json::error_handler_t::replace); }

// a JSON-RPC error answer, thrown while handling a request
struct RpcError : std::runtime_error {
    int code;
    json data;
    RpcError(int code, const std::string& msg, json data = nullptr) : std::runtime_error(msg), code(code), data(std::move(data)) {}
};
struct ScopeExit {
    std::function<void()> fn;
    ~ScopeExit() { fn(); }
};

