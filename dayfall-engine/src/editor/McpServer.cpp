std::string imageMime(const fs::path& p) {
    std::string e = p.extension().string();
    for (auto& c : e) c = (char)tolower((unsigned char)c);
    return e == ".jpg" || e == ".jpeg" ? "image/jpeg" : e == ".png" ? "image/png" : "";
}

struct CaptureFile { fs::path path; fs::file_time_type time; uintmax_t size; };
std::vector<CaptureFile> newestCaptures(const fs::path& mapDir, size_t max) {
    std::vector<CaptureFile> out;
    if (mapDir.empty()) return out;
    try {
        std::error_code ec;
        for (const auto& e : fs::directory_iterator(mapDir / "captures", ec))
            if (e.is_regular_file() && !imageMime(e.path()).empty()) out.push_back({e.path(), e.last_write_time(), e.file_size()});
    } catch (const fs::filesystem_error&) {}
    std::sort(out.begin(), out.end(), [](auto& a, auto& b) { return a.time > b.time; });
    if (out.size() > max) out.resize(max);
    return out;
}

